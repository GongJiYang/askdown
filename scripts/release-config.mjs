import { readFileSync, writeFileSync, appendFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const required = (name) => {
  const value = process.env[name];
  if (!value?.trim()) throw new Error(`Missing release configuration: ${name}`);
  return value.trim();
};
const config = JSON.parse(readFileSync('src-tauri/tauri.conf.json', 'utf8'));
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const cargo = readFileSync('src-tauri/Cargo.toml', 'utf8');
const cargoVersion = cargo.match(/^\[package\]([\s\S]*?)(?=^\[|$(?![\s\S]))/m)?.[1]
  .match(/^version\s*=\s*"([^"]+)"/m)?.[1];
const tag = required('RELEASE_TAG');
if (!/^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(tag)) {
  throw new Error('Release tags must be stable versions in vMAJOR.MINOR.PATCH format.');
}
if (tag !== `v${config.version}` || pkg.version !== config.version || cargoVersion !== config.version) {
  throw new Error('Release tag, package.json, Cargo.toml and tauri.conf.json versions must match.');
}
const repository = required('GITHUB_REPOSITORY');
if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository)) throw new Error('Invalid GitHub repository.');
const publicKey = required('TAURI_UPDATER_PUBLIC_KEY');
const decoded = Buffer.from(publicKey, 'base64').toString('utf8').trim().split(/\r?\n/);
if (decoded.length !== 2 || !decoded[0].startsWith('untrusted comment:') || Buffer.from(decoded[1], 'base64').length !== 42) {
  throw new Error('TAURI_UPDATER_PUBLIC_KEY must contain the complete base64 public key generated by tauri signer generate.');
}
if (process.argv.includes('--preflight')) {
  for (const name of [
    'TAURI_SIGNING_PRIVATE_KEY', 'TAURI_SIGNING_PRIVATE_KEY_PASSWORD',
    'APPLE_CERTIFICATE', 'APPLE_CERTIFICATE_PASSWORD', 'APPLE_SIGNING_IDENTITY',
    'APPLE_ID', 'APPLE_PASSWORD', 'APPLE_TEAM_ID',
  ]) required(name);
  if (!required('APPLE_SIGNING_IDENTITY').startsWith('Developer ID Application:')) {
    throw new Error('APPLE_SIGNING_IDENTITY must be a Developer ID Application identity, not ad-hoc or development signing.');
  }
  if (!/^[A-Z0-9]{10}$/.test(required('APPLE_TEAM_ID'))) throw new Error('Invalid Apple team ID.');
  const sha = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  appendFileSync(required('GITHUB_OUTPUT'), `tag=${tag}\nsha=${sha}\n`);
} else {
  writeFileSync('tauri.release.json', JSON.stringify({
    bundle: { createUpdaterArtifacts: true },
    plugins: { updater: {
      pubkey: publicKey,
      endpoints: [`https://github.com/${repository}/releases/latest/download/latest.json`],
    } },
  }, null, 2) + '\n');
  appendFileSync(required('GITHUB_ENV'), 'VITE_ASKDOWN_UPDATER_CONFIGURED=true\n');
}
console.log(`Release configuration validated for ${tag}.`);
